namespace UnifiedChart
{
    /// <summary>
    /// 系列のデータ点に表示するマーカー(シンボル)形状を表す。
    /// </summary>
    public enum MarkerShape
    {
        /// <summary>円形。</summary>
        Circle,

        /// <summary>塗りつぶし点。</summary>
        Dot,

        /// <summary>正方形。</summary>
        Square,

        /// <summary>枠付き正方形。</summary>
        Box,

        /// <summary>ひし形。</summary>
        Diamond,

        /// <summary>三角形。</summary>
        Triangle,

        /// <summary>逆三角形。</summary>
        InvertedTri,

        /// <summary>十字形(X字)。</summary>
        Cross,

        /// <summary>斜め十字形(X字)。</summary>
        DiagCross,

        /// <summary>十字形(プラス、+字)。</summary>
        Plus,

        /// <summary>星形。</summary>
        Star
    }
}
